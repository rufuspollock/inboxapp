async function imageFiles(directory, relative = '') {
  let entries;
  try { entries = await fs.readdir(path.join(directory, relative), { withFileTypes: true }); }
  catch (error) { if (error.code === 'ENOENT') return []; throw error; }
  const files = [];
  for (const entry of entries) {
    const name = path.join(relative, entry.name);
    if (entry.isDirectory()) files.push(...await imageFiles(directory, name));
    else if (entry.isFile()) files.push(name);
  }
  return files.sort();
}

export async function buildChangelog(root, { check = false } = {}) {
  const source = path.join(root, 'changelog');
  const output = path.join(root, 'site/changelog');
  const filenames = (await fs.readdir(source)).filter(name => /^\d{4}-\d{2}-\d{2}-.+\.md$/.test(name));
  const entries = await Promise.all(filenames.map(async name => entryFromMarkdown(name, await fs.readFile(path.join(source, name), 'utf8'))));
  entries.sort((a, b) => b.date.localeCompare(a.date) || b.id.localeCompare(a.id));
  const generated = new Map([['index.html', Buffer.from(render(entries))]]);
  for (const name of await imageFiles(path.join(source, 'images'))) {
    generated.set(path.join('images', name), await fs.readFile(path.join(source, 'images', name)));
  }
  if (check) {
    for (const [name, expected] of generated) {
      const actual = await fs.readFile(path.join(output, name)).catch(error => {
        if (error.code === 'ENOENT') return null;
        throw error;
      });
      if (!actual?.equals(expected)) throw new Error(`Stale site/changelog/${name}; run npm run build:site and commit the output`);
    }
    for (const name of await imageFiles(path.join(output, 'images'))) {
      if (!generated.has(path.join('images', name))) throw new Error(`Obsolete site/changelog/images/${name}; run npm run build:site`);
    }
    return;
  }
  await fs.mkdir(output, { recursive: true });
  await fs.rm(path.join(output, 'images'), { recursive: true, force: true });
  for (const [name, bytes] of generated) {
    await fs.mkdir(path.dirname(path.join(output, name)), { recursive: true });
    await fs.writeFile(path.join(output, name), bytes);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  await buildChangelog(root, { check: process.argv.includes('--check') });
}
