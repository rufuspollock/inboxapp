const escapeHtml = value => String(value).replace(/[&<>"']/g, character => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
}[character]));

function entryFromMarkdown(filename, source) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!match) throw new Error(`${filename}: missing YAML frontmatter`);
  const metadata = parse(match[1]);
  if (!metadata || typeof metadata.title !== 'string' || !metadata.title.trim()
      || !/^\d{4}-\d{2}-\d{2}$/.test(metadata.date)
      || typeof metadata.promote !== 'boolean') {
    throw new Error(`${filename}: expected date, plain-text title and boolean promote`);
  }
  const id = filename.slice(0, -3);
  // Sources are reviewed, version-controlled project prose, not user input.
  return { ...metadata, id, html: marked.parse(match[2]) };
}

